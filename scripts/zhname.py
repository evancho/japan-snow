def norm_key(value: str) -> str:
    text = unicodedata.normalize("NFKC", value or "")
    text = re.sub(r"[\s\u3000・･·\-‐‑–—&＆×＊*（）()「」『』\"'’]+", "", text)
    return text.casefold()


_OVERRIDE_NORM = {norm_key(k): v for k, v in OVERRIDES.items()}


def kata_to_hira(text: str) -> str:
    out = []
    for ch in text:
        code = ord(ch)
        if 0x30A1 <= code <= 0x30F6:
            out.append(chr(code - 0x60))
        elif ch == "ヴ":
            out.append("ゔ")
        else:
            out.append(ch)
    return "".join(out)


def load_kanji_map(path: Path | None = None) -> dict[str, str]:
    global _MAP
    if _MAP is not None and path is None:
        return _MAP
    if path is None:
        path = CACHE / "JPShinjitaiCharacters.txt"
    table: dict[str, str] = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) < 2:
                continue
            src, rest = parts[0], parts[1]
            choices = rest.split()
            if src in SKIP:
                table[src] = src
                continue
            pick = choices[0]
            if pick == src and len(choices) > 1 and src in SECOND_CHOICE:
                pick = choices[1]
            table[src] = pick
    table.update(EXTRA)
    for src in SKIP:
        table[src] = src
    if path is None or path == CACHE / "JPShinjitaiCharacters.txt":
        _MAP = table
    return table


def apply_kanji(text: str, table: dict[str, str] | None = None) -> str:
    table = table if table is not None else load_kanji_map()
    out = "".join(table.get(ch, ch) for ch in text)
    for src, dst in POST.items():
        out = out.replace(src, dst)
    return out


def _reading_keys() -> list[str]:
    global _READING_KEYS
    if _READING_KEYS is None:
        _READING_KEYS = sorted(READINGS, key=len, reverse=True)
    return _READING_KEYS


def _phonetic(span: str) -> str:
    i = 0
    out = []
    while i < len(span):
        if span[i] in "ーっ〜～ぁぃぅぇぉ":
            i += 1
            continue
        if i + 2 <= len(span) and span[i : i + 2] in DIGRAPH:
            out.append(DIGRAPH[span[i : i + 2]])
            i += 2
            continue
        ch = span[i]
        if ch in MORA:
            out.append(MORA[ch])
        elif ch not in "ーっ":
            out.append(ch)
        i += 1
    return "".join(out)


def _is_kana(ch: str) -> bool:
    code = ord(ch)
    return 0x3040 <= code <= 0x309F or ch in "ー〜～"


def _is_cjk(ch: str) -> bool:
    return "\u4e00" <= ch <= "\u9fff"


def convert_body(text: str) -> str:
    """Convert a Japanese name. Does not apply the famous-resort overrides."""
    raw = unicodedata.normalize("NFKC", text or "")
    raw = raw.replace("ヶ", "の").replace("ヵ", "の")
    raw = re.sub(r"[・･·．.]+", "", raw)
    raw = kata_to_hira(raw)
    for src, dst in (("びわ湖", "琵琶湖"), ("たざわ湖", "田澤湖")):
        raw = raw.replace(src, dst)
    keys = _reading_keys()
    out = []
    i = 0
    n = len(raw)
    while i < n:
        if _is_kana(raw[i]):
            j = i
            while j < n and _is_kana(raw[j]):
                j += 1
            span = raw[i:j]
            prev = raw[i - 1] if i else ""
            nxt = raw[j] if j < n else ""
            if span in {"の", "が", "け"} and _is_cjk(prev) and _is_cjk(nxt):
                out.append("之")
            else:
                k = 0
                while k < len(span):
                    hit = None
                    for key in keys:
                        if span.startswith(key, k):
                            hit = key
                            break
                    if hit:
                        out.append(READINGS[hit])
                        k += len(hit)
                    elif span[k] == "の":
                        out.append("之")
                        k += 1
                    elif span[k] in "ーっ〜～":
                        k += 1
                    else:
                        step = 2 if k + 1 < len(span) and span[k : k + 2] in DIGRAPH else 1
                        out.append(_phonetic(span[k : k + step]))
                        k += step
            i = j
        else:
            out.append(raw[i])
            i += 1
    return apply_kanji("".join(out))


def polish(text: str) -> str:
    value = re.sub(r"[（(][^）)]*[）)]", "", text)
    value = value.replace("（株）", "").replace("(株)", "")
    value = re.sub(r"之{2,}", "之", value)
    value = re.sub(r"\s+", "", value)
    changed = True
    while changed:
        changed = False
        for suffix in TRAIL:
            if value.endswith(suffix) and len(value) - len(suffix) >= 2:
                core = value[: -len(suffix)]
                if core not in KEEP_CORE:
                    value = core
                    changed = True
                    break
    return value


def to_zh(name: str) -> str:
    key = norm_key(name)
    if key in _OVERRIDE_NORM:
        return _OVERRIDE_NORM[key][0]
    return polish(convert_body(name))


def override_meta(name: str) -> tuple[str, list[str], str | None] | None:
    return _OVERRIDE_NORM.get(norm_key(name))


def romaji(text: str) -> str:
    raw = kata_to_hira(unicodedata.normalize("NFKC", text or ""))
    out = []
    i = 0
    while i < len(raw):
        if raw[i] == "っ" and i + 1 < len(raw):
            nxt = None
            if i + 3 <= len(raw) and raw[i + 1 : i + 3] in ROMA_DIG:
                nxt = ROMA_DIG[raw[i + 1 : i + 3]]
            elif raw[i + 1] in ROMA:
                nxt = ROMA[raw[i + 1]]
            if nxt:
                out.append(nxt[0])
            i += 1
            continue
        if raw[i] in "ー〜～":
            i += 1
            continue
        if i + 2 <= len(raw) and raw[i : i + 2] in ROMA_DIG:
            out.append(ROMA_DIG[raw[i : i + 2]])
            i += 2
            continue
        if raw[i] in ROMA:
            out.append(ROMA[raw[i]])
            i += 1
            continue
        if raw[i].isascii() and raw[i].isalnum():
            out.append(raw[i].lower())
        i += 1
    return "".join(out)


